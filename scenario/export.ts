import type { Db } from '../src/db.ts'
import { many } from '../src/db.ts'
import { T0 } from '../src/seed.ts'

const clock = (d: Date) => {
  const s = Math.round((new Date(d).getTime() - T0.getTime()) / 1000)
  const h = 9 + Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), sec = s % 60
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}${sec ? ':' + String(sec).padStart(2, '0') : ''}`
}

export async function exportTrace(db: Db) {
  const rows = await many(db, 'select * from app.trace order by seq')
  const pids = [...new Set(rows.filter(r => r.kind === 'process').map(r => r.pid))]
  const steps = rows.map(r => ({ seq: Number(r.seq), time: clock(r.at), process: pids.indexOf(r.pid) + 1, actor: r.actor, kind: r.kind, step: r.step, detail: r.detail }))
  const state = {
    booking: await many(db, 'select id, title, guests, discount_pct, total_cents, version, last_change_provenance, last_action_key from app.bookings'),
    workItems: await many(db, 'select id, kind, title, status, waiting_for, mastra_resource, mastra_thread from app.work_items order by id'),
    sources: await many(db, 'select * from app.work_sources order by work_item_id, message_id'),
    authorisations: await many(db, 'select id, work_item_id, max_pct, scope, granted_by, source_message_id from app.discount_authorizations'),
    proposals: await many(db, 'select id, revision, based_on_booking_version, effects, reply_to, reply_subject, reply_body, content_hash, status, status_reason, mastra_run_id from app.proposals order by id'),
    approvals: await many(db, 'select id, proposal_id, content_hash, approved_by, consumed_by_action from app.approvals order by id'),
    actions: await many(db, 'select key, status, attempts, provider_message_id from app.actions'),
    providerMessages: await many(db, 'select id, idempotency_key, to_addr, subject from provider.messages'),
    snapshots: undefined as any,
    mastraThreads: await many(db, `select id, "resourceId" from mastra.mastra_threads order by id`).catch(() => []),
  }
  const snapshots = await many(db, 'select label, data from app.snapshots order by seq')
  delete (state as any).snapshots
  const md = ['# Scenario trace', '', 'Generated by `npm run scenario`. Times are simulated; each process is a separate OS process.', '',
    '| time | proc | actor | step | detail |', '|---|---|---|---|---|',
    ...steps.map(s => `| ${s.time} | ${s.process || 'setup'} | ${s.actor} | ${s.step} | ${Object.entries(s.detail).map(([k, v]) => `${k}: ${typeof v === 'string' ? v : JSON.stringify(v)}`).join('; ').replace(/\|/g, '/').replace(/\n/g, ' ')} |`),
    '', '## What is left in Postgres', '', '```json', JSON.stringify(state, null, 2), '```', ''].join('\n')
  return { generatedAt: new Date().toISOString(), steps, state, snapshots, markdown: md }
}
